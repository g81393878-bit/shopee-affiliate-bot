def intro_posts() -> list:
    """คืน list ของ dict {title, caption, image_url} — แทนลิงก์ LINE OA จริงแล้ว (ลำดับตาม _POSTS).

    caption = ป้ายข้อความ (badge) + เนื้อโพสต์
    image_url = รูปมาสคอตป้าเข็ม (โฮสต์เองที่ /static/) — แนบรูปด้วย post_feed(image_url=...)
    """
    line_oa = (os.getenv("LINE_OA_URL") or "").strip() or _LINE_PLACEHOLDER
    image_url = (os.getenv("INTRO_IMAGE_URL") or "").strip() or _INTRO_IMAGE_URL
    out = []
    for p in _POSTS:
        caption = p["caption"].replace(_LINE_PLACEHOLDER, line_oa)
        badge = (p.get("badge") or "").strip()
        # หัวโพสต์แนะนำทุกตัว: ป้ายกำกับชัดเจน แยกจากโพสต์ขายสินค้า (เจ้าของสั่ง 18/08)
        label = "👵 โพสต์แนะนำบอท"
        if badge:
            caption = f"{label} | 🏷️ {badge}\n\n{caption}"
        else:
            caption = f"{label}\n\n{caption}"
        out.append({"title": p["title"], "caption": caption, "image_url": image_url})
    return out


