def normalize_query(q: str) -> str:
    """คำพ้อง/การันต์/พิมพ์ผิด → แบบมาตรฐาน (ใช้ทั้งคำค้นและชื่อก่อนจัดหมวด)"""
    for a, b in THAI_VARIANT_MAP.items():
        q = q.replace(a, b)
    return q


def guess_category(name: str) -> str:
    """'หูฟังไม่เกิน 300' → 'หูฟัง', 'กระติก 2 ลิตร' → 'แก้วน้ำ', ไม่ตรง → 'อื่นๆ'.
    ใช้คำค้นที่ยาวที่สุด (เฉพาะที่สุด) ชนะ — กัน "จาน" (เครื่องครัว) มาก่อน
    "น้ำยาล้างจาน" (ของใช้บ้าน) เพราะคำสั้นๆ อยู่ในคำยาวเสมอ
    2 รอบ: รอบแรกข้ามคำเทคกลางๆ (bluetooth/usb/กันแดด...) เพื่อให้คำเฉพาะของ
    สินค้าชนะ (เมาส์ ≠ หูฟัง); รอบสองใช้คำเทคเป็นตัวสำรอง (ไฟโซล่า ยังเป็นโคมไฟ)"""
    n = normalize_query((name or "").lower())
    cat = _best_category(n, skip_generic=True)
    if cat != "อื่นๆ":
        return cat
    return _best_category(n, skip_generic=False)
