def _word_boundary_ok(n: str, kw: str, pos: int) -> bool:
    """กัน keyword สั้น (≤3 ตัว) แมตช์กลางคำไทย/อังกฤษ: 'นม' ใน 'กันมอง' → ไม่นับ
    (คำยาว ≥4 ตัวเฉพาะพอ ไม่ต้องเช็กขอบ)"""
    if n.count(kw) >= 2:
        return True
    if pos > 0 and 0x0E00 <= ord(n[pos - 1]) <= 0x0E7F:
        return False  # ติดกับตัวอักษรไทยก่อนหน้า = กลางคำไทย
    after = n[pos + len(kw):pos + len(kw) + 1]
    if after and after.isalnum() and not (0x0E00 <= ord(after) <= 0x0E7F):
        return False  # ติดกับตัวละติน = กลางคำอังกฤษ
    return True


def _best_category(n: str, skip_generic: bool) -> str:
    best = (0, "อื่นๆ")
    for kw, cat in CATEGORY_KEYWORDS:
        pos = n.find(kw)
        if pos < 0 or len(kw) <= best[0]:
            continue
        if skip_generic and kw in GENERIC_TECH_WORDS:
            continue
        if len(kw) < 4 and not _word_boundary_ok(n, kw, pos):
            continue
        best = (len(kw), cat)
    return best[1]


