def _word_boundary_ok(n: str, kw: str, pos: int) -> bool:
    """กัน keyword สั้น (≤3 ตัว) แมตช์กลางคำไทย/อังกฤษ: 'นม' ใน 'กันมอง' → ไม่นับ
    (คำยาว ≥4 ตัวเฉพาะพอ ไม่ต้องเช็กขอบ) — ตัวเลขตามหลังไม่นับเป็นกลางคำ
    ('เทป2หน้า', 'แมส3D' ยังผ่าน)"""
    if n.count(kw) >= 2:
        return True
    if pos > 0 and 0x0E00 <= ord(n[pos - 1]) <= 0x0E7F:
        return False  # ติดกับตัวอักษรไทยก่อนหน้า = กลางคำไทย
    after = n[pos + len(kw):pos + len(kw) + 1]
    if after and ('a' <= after <= 'z' or 'A' <= after <= 'Z'):
        return False  # ติดกับตัวละติน = กลางคำอังกฤษ
    return True


