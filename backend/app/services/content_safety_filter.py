def is_sensitive_forbidden_topic(text: str) -> bool:
    """คืน True หากพบคำต้องห้าม (การเมือง / กษัตริย์ / 112 / ความรุนแรง)"""
    if not text:
        return False
    norm = text.lower()
    for kw in FORBIDDEN_KEYWORDS:
        if kw in norm:
            return True
    return False


def get_sensitive_matched_word(text: str) -> Optional[str]:
    """คืนคำต้องห้ามที่ตรวจพบ เพื่อการ log และแจ้งเตือน"""
    if not text:
        return None
    norm = text.lower()
    for kw in FORBIDDEN_KEYWORDS:
        if kw in norm:
            return kw
    return None
