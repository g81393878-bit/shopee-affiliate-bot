def persona_system_prompt(base: str = "") -> str:
    """System prompt = บุคลิกป้าเข็ม + หน้าที่ของโมเดล"""
    parts = [PERSONA_PROMPT]
    if base:
        parts.append(base)
    return "\n\n".join(parts)
