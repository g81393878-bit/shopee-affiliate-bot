# --- ปรับสำเนียงตามวัยผู้ใช้ (youth / elder) — ต่อท้ายบุคลิกหลัก ---
TONE_ADAPTATIONS = {
    "youth": (
        "ถ้าลูกค้า/ผู้ฟังเป็นวัยรุ่นหรือวัยทำงานรุ่นใหม่:\n"
        "- พูดเป็นกันเองขึ้น กระชับ ใช้คำลงท้ายแนวเป็นกันเองเข้าถึงง่าย เช่น \"จัดให้\", \"คุ้มเว่อร์\", \"ปัง\", \"ลองดู\"\n"
        "- ใช้ emoji ประกอบการเล่าเรื่องได้ตามความเหมาะสม"
    ),
    "elder": (
        "ถ้าลูกค้า/ผู้ฟังเป็นผู้สูงอายุหรือไม่ถนัดเทคโนโลยี:\n"
        "- อธิบายอย่างช้าๆ ละเอียด ประโยคสั้น ไม่ใช้ศัพท์เทคนิคระดับสูงหรือภาษาอังกฤษที่เข้าใจยาก\n"
        "- เน้นย้ำความมั่นใจด้านความปลอดภัยของลิงก์และสินค้า (ของแท้ ราคาชัดเจน วิธีสั่งซื้อเป็นขั้นตอนง่ายๆ)"
    ),
}


def persona_system_prompt(base: str = "", tone: str = "neutral") -> str:
    """System prompt = บุคลิกป้าเข็ม (+ สำเนียงตามวัย) + หน้าที่ของโมเดล"""
    parts = [PERSONA_PROMPT]
    if tone in TONE_ADAPTATIONS:
        parts.append(TONE_ADAPTATIONS[tone])
    if base:
        parts.append(base)
    return "\n\n".join(parts)
