# -*- coding: utf-8 -*-
"""สถานะร้าน — ศูนย์ความจริงเดียว (Single Source of Truth) เรื่อง "ปิดการขาย".

ร้านป้าเข็ม **ยุติการจำหน่ายทุกรายการแล้ว** จึงต้องไม่มีราคา/แพ็กเกจ/COD/เลขบัญชี
หลุดออกไปหาลูกค้าจากที่ใดเลย ทุกโมดูลที่ส่งข้อความหาลูกค้าต้องเรียก `closed_notice()`
แทนการเขียนข้อความเอง เพื่อไม่ให้ข้อความกระจายและขัดกันอีก

เปิด/ปิดด้วย env `SALES_CLOSED` (ค่าเริ่มต้น = ปิดการขาย):
    SALES_CLOSED=0  → เปิดการขาย (ทุกฟังก์ชันจะคืน False/"" ให้โค้ดเดิมทำงาน)
"""
import os

_FALSEY = ("0", "false", "no", "off", "")


def is_sales_closed() -> bool:
    """True = ยุติการจำหน่าย (ค่าเริ่มต้น) — อ่านจาก env SALES_CLOSED."""
    return (os.getenv("SALES_CLOSED", "1") or "").strip().lower() not in _FALSEY


SALES_CLOSED: bool = is_sales_closed()

# ข้อความมาตรฐาน: ไม่มีราคา ไม่มีแพ็กเกจ ไม่มีเลขบัญชี ไม่มีลิงก์สั่งซื้อ
CLOSED_NOTICE = (
    "🙏 สวัสดีค่ะ ขอขอบพระคุณที่ให้ความสนใจร้านป้าเข็มนะคะ\n\n"
    "ขณะนี้ทางร้านได้ยุติการจำหน่ายสินค้าและปิดรับออเดอร์ทุกรายการเรียบร้อยแล้วค่ะ "
    "จึงไม่มีสินค้าจำหน่ายและไม่มีราคาให้เสนอในขณะนี้\n\n"
    "กราบขออภัยในความไม่สะดวกเป็นอย่างยิ่ง และขอขอบพระคุณทุกท่านที่ให้การสนับสนุนด้วยดีตลอดมานะคะ ❤️"
)

# ใช้กับคอมเมนต์ (สั้นกว่า) — ยังไม่มีราคา/แพ็กเกจเช่นกัน
CLOSED_COMMENT_NOTICE = (
    "🙏 ขอบพระคุณที่ให้ความสนใจนะคะ ขณะนี้ทางร้านยุติการจำหน่ายและปิดรับออเดอร์ทุกรายการแล้วค่ะ "
    "จึงยังไม่มีสินค้าและราคาให้เสนอในตอนนี้ ขออภัยด้วยนะคะ ❤️"
)


def closed_notice() -> str:
    """ข้อความปิดการขายแบบเต็ม (ใช้ในแชท) — "" ถ้าเปิดขายอยู่."""
    return CLOSED_NOTICE if is_sales_closed() else ""


def closed_comment_notice() -> str:
    """ข้อความปิดการขายแบบสั้น (ใช้ในคอมเมนต์) — "" ถ้าเปิดขายอยู่."""
    return CLOSED_COMMENT_NOTICE if is_sales_closed() else ""


# ตาข่ายกันราคาหลุด (Safety net): ข้อความที่จะส่งหาลูกค้าที่มีราคา/COD/เลขบัญชี ถูกแทนที่
import re as _re

_PRICE_LEAK_RE = _re.compile(
    r"(?:390|410|450|470|490|510|550|570|630|650|680|1,?090)\s*\.?-?"
    r"|COD|เก็บเงินปลายทาง|เก็บปลายทาง|038-0-25363-1"
)


def mask_sales_text(text: str) -> str:
    """ถ้าปิดการขายและข้อความยังมีราคา/COD → คืนข้อความปิดการขายแทน.

    ใช้ที่ชั้นส่งข้อความ (send funnel) เป็นด่านสุดท้าย กันราคาหลุดจากโค้ดเก่า
    หรือการแก้ไขในอนาคต
    """
    if not is_sales_closed():
        return text
    if text and _PRICE_LEAK_RE.search(text):
        return CLOSED_NOTICE
    return text
