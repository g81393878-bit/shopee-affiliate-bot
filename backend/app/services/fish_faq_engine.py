    """
    ตรวจสอบว่าข้อความของลูกค้าตรงกับกฎข้อไหนใน data/fish_faq_rules.csv หรือไม่
    หากตรง คืนค่า dict ที่มี category, strategy_note, comment_reply, inbox_prefix
    """
    lower_text = (comment_text or "").lower().strip()
    if not lower_text:
        return None

    question_markers = ["ไหม", "มั้ย", "ป่าว", "เปล่า", "เหรอ", "หรือคะ", "เท่าไหร่", "ยังไง", "ที่ไหน", "บ่น้อ", "บ่จ้า", "บ่คะ", "บ่ครับ", "จักบาท", "?"]
    is_question = any(q in lower_text for q in question_markers)

    for rule in load_faq_rules():
        req_not_q = str(rule.get("require_not_question") or "").strip().upper() == "TRUE"
        if req_not_q and is_question:
            continue

        excl_raw = (rule.get("exclude_keywords") or "").strip()
        if excl_raw:
            excl_list = [k.strip().lower() for k in excl_raw.split("|") if k.strip()]
            if any(ek in lower_text for ek in excl_list):
                continue

        kw_raw = (rule.get("keywords") or "").strip()
        kw_list = [k.strip().lower() for k in kw_raw.split("|") if k.strip()]
        if any(kw in lower_text for kw in kw_list):
            tpl = (rule.get("comment_reply_template") or "").replace("\\n", "\n")
            inbox_tpl = (rule.get("inbox_prefix_template") or "").replace("\\n", "\n").strip()
            comment_reply = tpl.format(greeting=greeting, web_url=web_url)
            return {
                "rule_id": rule.get("rule_id") or "",
                "category": rule.get("category") or "💬 สอบถามทั่วไป",
                "strategy_note": rule.get("strategy_note") or "",
                "comment_reply": comment_reply,
                "inbox_prefix": (inbox_tpl + "\n\n") if inbox_tpl else "",
            }
    return None
