def test_skeptical_case_count_is_200():
    assert len(SKEPTICAL_CASES) == 200, f"ต้องมี 200 คน ตอนนี้ {len(SKEPTICAL_CASES)}"


@pytest.mark.parametrize("expected,text", SKEPTICAL_CASES)
def test_skeptical_customers(sim, expected, text):
    r = sim.send("U_cust_1", text)
    assert r["intent"] == expected, \
        f"{text!r} → intent={r['intent']} (คาด {expected}) preview={r['preview'][:60]!r}"
    assert r["preview"].strip(), f"{text!r} ตอบว่าง"


@pytest.mark.parametrize("expected,text",
                         [c for c in SKEPTICAL_CASES if c[0] == "manual"])
def test_skeptical_manual_replies_no_escalation(sim, expected, text):
    r = sim.send("U_cust_1", text)
    for bad in HUMAN_ESCALATION_WORDS:
        assert bad not in r["preview"], f"{text!r} ยังมี '{bad}': {r['preview'][:120]!r}"


@pytest.mark.parametrize("text", CASUAL_TEXTS)
def test_casual_customers_no_owner_push(sim, text):
    r = sim.send("U_cust_1", text)
    assert r["preview"].strip(), f"{text!r} ตอบว่าง"
    assert r["owner_pushes"] == [], f"{text!r} ปลุกเจ้าของทั้งที่ลูกค้าสบาย ๆ"
    assert r["intent"] != "unknown", f"{text!r} intent ไม่รู้จัก"
